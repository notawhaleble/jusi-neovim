vim.opt.runtimepath:prepend(vim.fn.getcwd() .. "/runtime")
vim.opt.runtimepath:append(vim.fn.getcwd() .. "/packages/jusi-web.nvim")
vim.cmd("runtime plugin/jusi_neovim.lua")
vim.cmd("runtime plugin/jusi_web.lua")
vim.cmd("JusiWebPrivate! https://example.com")
assert(vim.wait(1000, function() return vim.b.jusi_buffer_kind == "web" end))
local native = require("jusi_neovim.native-child")
local epoch, token = string.rep("e", 36), string.rep("t", 36)
local source = { bufferId = vim.api.nvim_get_current_buf(), incarnation = vim.b.jusi_incarnation }
native.connect(epoch)
local function request(sequence)
 return { epoch = epoch, sequence = sequence, token = token, source = source, url = "https://example.com/?literal=|tabnew" }
end
native.cancel(request(2))
assert(native.allocate(request(1)) == false)
assert(native.allocate(request(2)) == false)
local source_window = vim.api.nvim_get_current_win()
local tabs = #vim.api.nvim_list_tabpages()
local child = native.allocate(request(3))
assert(#vim.api.nvim_list_tabpages() == tabs, "Popup must not create a tab")
assert(vim.api.nvim_win_get_config(child.windowId).relative == "")
assert(vim.api.nvim_win_get_buf(source_window) == source.bufferId)
vim.o.columns = 60
vim.o.lines = 20
vim.api.nvim_exec_autocmds("VimResized", {})
local resized = vim.api.nvim_win_get_config(child.windowId)
assert(resized.relative == "", "Resize keeps an ordinary split; desktop verifies real grid bounds")
assert(child and vim.b[child.bufferId].jusi_native_child == token)
assert(vim.b[child.bufferId].jusi_browser_private and vim.b[child.bufferId].jusi_text_layer == "off")
local mode_request = { epoch = epoch, sequence = 3, token = token,
  bufferId = child.bufferId, incarnation = child.incarnation, mode = "rich" }
vim.api.nvim_set_current_win(source_window)
assert(native.set_mode(mode_request))
assert(vim.api.nvim_get_current_win() == child.windowId)
mode_request.token = "forged"
assert(native.set_mode(mode_request) == false)
mode_request.token = token
vim.cmd("tabnew")
assert(native.set_mode(mode_request) == false, "Hidden child must not steal focus")
vim.cmd("tabclose")
mode_request.mode = "text"
assert(native.set_mode(mode_request))
native.cancel(request(3))
assert(native.set_mode(mode_request) == false)
assert(not vim.api.nvim_buf_is_valid(child.bufferId))
assert(vim.api.nvim_buf_is_valid(source.bufferId))
child = native.allocate(request(4))
_G.jusi_neovim_open_surface(child.bufferId, "https://replacement.test", {})
native.cancel(request(4))
assert(vim.api.nvim_buf_is_valid(child.bufferId), "Cancellation must not delete a replacement incarnation")
assert(vim.b[child.bufferId].jusi_native_child == nil)
vim.api.nvim_buf_delete(child.bufferId, { force = true })
local stale = request(5); stale.source = { bufferId = source.bufferId, incarnation = source.incarnation + 1 }
assert(native.allocate(stale) == false)
child = native.allocate(request(6))
vim.api.nvim_win_close(child.windowId, true)
assert(not vim.api.nvim_buf_is_valid(child.bufferId), "Closing float must wipe auxiliary buffer")
assert(vim.api.nvim_get_current_win() == source_window)
child = native.allocate(request(7))
native.connect(string.rep("n", 36))
assert(not vim.api.nvim_buf_is_valid(child.bufferId))
assert(native.allocate(request(8)) == false)
epoch = string.rep("n", 36)
vim.cmd("tabnew")
assert(native.allocate(request(1)) == false, "Hidden source must not open in another tab")
vim.cmd("tabclose")
child = native.allocate(request(2))
vim.o.columns = 10
vim.api.nvim_exec_autocmds("VimResized", {})
assert(vim.api.nvim_buf_is_valid(child.bufferId), "Neovim owns split resizing")
native.cancel(request(2))
assert(vim.api.nvim_buf_is_valid(source.bufferId))
print("native child allocation/cancellation and split window tests passed")
