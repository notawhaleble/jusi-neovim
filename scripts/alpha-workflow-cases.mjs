import assert from 'node:assert/strict';
import { webContents } from 'electron';
import { browserCommandCases, browserFocusCases } from './browser-interaction-cases.mjs';

/** One default-adapter everyday workflow, reusing common command/focus cases. */
export async function alphaWorkflowCases({host,guest,command,waitFor,url}) {
  const js=code=>host.webContents.executeJavaScript(code);
  const state=()=>js('window.jusi.getInitialState()');
  const selector='.web-view-box:not(.web-view-box--parked) .presentation-text-status';
  const status=expected=>waitFor(()=>js(`document.querySelector(${JSON.stringify(selector)})?.dataset.status===${JSON.stringify(expected)}`));
  const active=s=>s.snapshot.tabs.find(t=>t.id===s.snapshot.currentTabId)?.currentWindowId;
  const press=(target,keyCode,modifiers=[])=>{for(const type of ['keyDown','keyUp'])target.sendInputEvent({type,keyCode,modifiers});};
  const enter=async target=>{await js(`window.jusi.sendInput('i')`);await waitFor(()=>target.executeJavaScript('document.hasFocus()'));};
  const leave=async target=>{press(target,'\\',['control']);press(target,'N',['control']);await waitFor(()=>target.executeJavaScript('!document.hasFocus()'));};
  const type=async(target,text)=>{for(const keyCode of text){target.sendInputEvent({type:'keyDown',keyCode});target.sendInputEvent({type:'char',keyCode});target.sendInputEvent({type:'keyUp',keyCode});}};
  const value=()=>guest.executeJavaScript(`document.querySelector('input').value`);
  const attach=async bufferId=>waitFor(async()=>{const s=await state();const windowId=active(s);if(!s.attachedWebViews.some(v=>v.bufferId===bufferId&&v.windowId===windowId))return false;return js(`!!document.querySelector('.web-view-box:not(.web-view-box--parked)[data-window-id="${windowId}"] webview')`);});
  let phase='commands';
  try {
    await browserCommandCases({host,guest,waitFor,statusSelector:selector});
    await browserFocusCases({host,guest,waitFor});
    phase='link navigation';
    await guest.executeJavaScript(`(()=>{const a=document.createElement('a');a.id='workflow-link';a.href=${JSON.stringify(url+'next')};a.textContent='Next page';document.body.append(a)})()`);
    await enter(guest);
    const point=await guest.executeJavaScript(`(()=>{const r=document.querySelector('#workflow-link').getBoundingClientRect();return {x:Math.round(r.left+10),y:Math.round(r.top+r.height/2)}})()`);
    guest.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...point});
    guest.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...point});
    await waitFor(()=>guest.getURL()===url+'next');await status('ready');
    press(guest,'O',['control']);await waitFor(()=>guest.getURL()===url);await status('ready');
    press(guest,'I',['control']);await waitFor(()=>guest.getURL()===url+'next');await status('ready');
    await leave(guest);
    phase='retained form';
    const initial=await state(),binding=initial.attachedWebViews.find(v=>v.windowId===active(initial));
    assert.ok(binding);const originalGuestId=guest.id;
    await enter(guest);await guest.executeJavaScript(`document.querySelector('input').focus()`);
    await type(guest,'alpha');await waitFor(async()=>await value()==='alpha');await leave(guest);
    await enter(guest);assert.equal(await value(),'alpha');await type(guest,'b');await waitFor(async()=>await value()==='alphab');await leave(guest);
    phase='tabs';
    await command('tab split');await attach(binding.bufferId);
    assert.equal(await js(`document.querySelector('.web-view-box:not(.web-view-box--parked) webview').getWebContentsId()`),originalGuestId);
    await command('tabnew');
    await command(`lua vim.api.nvim_buf_set_lines(0,0,-1,false,{'editor one','editor two','editor three'}); vim.api.nvim_win_set_cursor(0,{1,0})`);
    await waitFor(()=>js(`!!document.querySelector('.web-view-box--parked webview')`));
    await js(`window.jusi.sendInput('j')`);
    await waitFor(async()=>{try {await command('lua assert(vim.api.nvim_win_get_cursor(0)[1] == 2)');return true;}catch{return false;}});
    assert.equal(await guest.executeJavaScript('document.hasFocus()'),false);
    assert.equal(await value(),'alphab');
    await command('tabclose!');await attach(binding.bufferId);
    await command('tabclose');await attach(binding.bufferId);
    phase='split ownership';
    await command('vnew');
    await waitFor(async()=>active(await state())!==binding.windowId);
    const split=await state(),editorWindow=active(split);
    assert.notEqual(editorWindow,binding.windowId);
    assert.equal(split.attachedWebViews.find(v=>v.bufferId===binding.bufferId)?.windowId,binding.windowId);
    await command(`lua vim.api.nvim_buf_set_lines(0,0,-1,false,{'split one','split two'}); vim.api.nvim_win_set_cursor(0,{1,0})`);
    await js(`window.jusi.sendInput('j')`);
    await waitFor(async()=>{try {await command(`lua assert(vim.api.nvim_win_get_cursor(${editorWindow})[1] == 2)`);return true;}catch{return false;}});
    assert.equal(await value(),'alphab');
    await command('wincmd p');await attach(binding.bufferId);
    await enter(guest);await type(guest,'c');await waitFor(async()=>await value()==='alphabc');await leave(guest);
    await command(`lua vim.api.nvim_win_close(${editorWindow},true)`);await attach(binding.bufferId);
    phase='failed text and retry';
    await guest.executeJavaScript(`window.workflowStyle=window.getComputedStyle;window.getComputedStyle=()=>{throw Error('workflow extraction failure')};void 0`);
    await js(`document.querySelector(${JSON.stringify(selector)}).click()`);await status('error');
    await enter(guest);await type(guest,'d');await waitFor(async()=>await value()==='alphabcd');await leave(guest);
    await guest.executeJavaScript(`window.getComputedStyle=window.workflowStyle;delete window.workflowStyle`);
    await js(`document.querySelector(${JSON.stringify(selector)}).click()`);await status('ready');
    assert.equal(await value(),'alphabcd');
    phase='text off and close';
    await command(`JusiWebBuffer! ${url}`);await status('disabled');
    const off=await waitFor(()=>webContents.getAllWebContents().find(c=>c.getType()==='webview'&&c.id!==guest.id&&c.getURL()===url));
    assert.equal(await off.executeJavaScript('typeof window.__jusiDocumentChanges'),'undefined');
    await enter(off);await off.executeJavaScript(`document.querySelector('input').focus()`);await type(off,'off');
    await waitFor(()=>off.executeJavaScript(`document.querySelector('input').value==='off'`));
    press(off,'Q',['control']);await waitFor(()=>off.isDestroyed());
    await command(`buffer ${binding.bufferId}`);await attach(binding.bufferId);await status('ready');
    assert.equal(await value(),'alphabcd');
    await command('JusiClose');await waitFor(()=>guest.isDestroyed());
    phase='reopen';
    await command(`JusiWebBuffer ${url}`);await status('ready');
    const reopened=await waitFor(()=>webContents.getAllWebContents().find(c=>c.getType()==='webview'&&c.getURL()===url));
    assert.notEqual(reopened.id,originalGuestId);
    const current=await state();assert.notEqual(current.attachedWebViews.find(v=>v.windowId===active(current))?.sessionId,binding.sessionId);
    await enter(reopened);await reopened.executeJavaScript(`document.querySelector('input').focus()`);await type(reopened,'new');
    await waitFor(()=>reopened.executeJavaScript(`document.querySelector('input').value==='new'`));
    await leave(reopened);await command('JusiClose');await waitFor(()=>reopened.isDestroyed());
    console.log('Local alpha everyday workflow passed: navigation, form retention, tabs/splits, failed-text retry, text off, close/reopen');
  } catch(error) {
    console.error('Alpha workflow failure',phase,await js(`(async()=>{const s=await window.jusi.getInitialState();return {windows:s.snapshot.windows,tabs:s.snapshot.tabs,views:s.attachedWebViews.map(v=>({bufferId:v.bufferId,windowId:v.windowId,sessionId:v.sessionId})),status:document.querySelector(${JSON.stringify(selector)})?.textContent}})()`));
    throw error;
  }
}
