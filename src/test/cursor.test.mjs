import assert from 'node:assert/strict';
import {cursorCell,cursorHighlight,cursorBlink,updateCursorBlink,hideCursor,restartCursorBlink} from '../../dist/renderer/cursor.js';
const runs=[{text:'ab',columns:2,highlightId:1},{text:'é',columns:1,highlightId:2},{text:'文',columns:2,highlightId:3},{text:'👩‍💻',columns:2,highlightId:4}];
assert.deepEqual(cursorCell(runs,1),{text:'b',columns:1,offset:0,highlightId:1});
assert.equal(cursorCell(runs,2).text,'é');
assert.deepEqual(cursorCell(runs,4),{text:'文',columns:2,offset:1,highlightId:3});
assert.equal(cursorCell(runs,5).text,'👩‍💻');
assert.equal(cursorCell(runs,20).text,' ');
const defaults={foreground:'#ffffff',background:'#000000'};
assert.deepEqual(cursorHighlight({}, {foreground:'#ff0000',background:'#00ff00',bold:true}, {},defaults),{foreground:'#00ff00',background:'#ff0000',bold:true,reverse:false});
assert.deepEqual(cursorHighlight({}, {reverse:true}, {},defaults),{...defaults,reverse:false});
assert.deepEqual(cursorHighlight({attrId:7},undefined,{7:{background:'#ff0000'}},defaults),{foreground:'#ffffff',background:'#ff0000'});
const style={shape:'block',cellPercentage:100,blinkWait:700,blinkOff:400,blinkOn:250};
assert.deepEqual(cursorBlink(style),{delay:700,duration:650,offFraction:400/650});
for(const key of ['blinkWait','blinkOn','blinkOff']) assert.equal(cursorBlink({...style,[key]:0}),null);
let created=0,cancelled=0;
const element={style:{},animate(){created++;return {currentTime:123,cancel(){cancelled++}}}};
updateCursorBlink(element,style,'grid:2:0:1');
updateCursorBlink(element,style,'grid:2:0:1');
assert.equal(created,1,'unrelated redraw retains animation');
restartCursorBlink(element);
updateCursorBlink(element,style,'grid:2:0:2');
assert.equal(created,2);assert.equal(cancelled,1);
hideCursor(element);assert.equal(cancelled,2);assert.equal(element.style.display,'none');
updateCursorBlink(element,style,'grid:2:0:2');assert.equal(created,3,'reappearance restarts blinkwait');
console.log('Cursor cells, inversion, timing and lifecycle passed');
