import assert from 'node:assert/strict';
import { runInNewContext } from 'node:vm';
import { documentChangesSource } from '../../dist/backends/web/document-changes.js';
let callback, options, removed=0, clock=0, serial=0;
const timers=new Map();
const setTimeout=(fn,delay)=>{const id=++serial;timers.set(id,{fn,at:clock+delay});return id;};
const clearTimeout=id=>timers.delete(id);
const tick=ms=>{clock+=ms;for(const [id,t] of [...timers])if(t.at<=clock&&timers.delete(id))t.fn();};
const document={getElementById:()=>({remove:()=>removed++}),fonts:{addEventListener:()=>{}}};
const window={addEventListener:()=>{},__jusiMirrorIndexMap:[1],__jusiTextJobId:1,__jusiTextStyles:new WeakMap()};
const context={document,window,setTimeout,clearTimeout,getComputedStyle:e=>e.style??{},MutationObserver:class {constructor(fn){callback=fn;}observe(_,opts){options=opts;}}};
const read=()=>runInNewContext(documentChangesSource(),context);
assert.equal(read(),0);assert.equal(options.subtree,true);
const own={nodeType:1,closest:selector=>selector.includes('#jusi-')},foreign={nodeType:1,closest:()=>false,textContent:'text'};
callback([{type:'childList',target:foreign,addedNodes:[own],removedNodes:[]}]);
callback([{type:'attributes',target:own}]);tick(500);
assert.equal(read(),0,'host decorations do not invalidate');
callback([{type:'characterData',target:{nodeType:3,parentElement:foreign}}]);
assert.equal(window.__jusiTextJobId,2);assert.equal(window.__jusiMirrorIndexMap.length,0);assert.equal(removed,1);
assert.equal(read(),0,'publication waits for a quiet interval');tick(400);assert.equal(read(),1);
callback([{type:'childList',target:foreign,addedNodes:[],removedNodes:[foreign]}]);tick(400);assert.equal(read(),2);
assert(!options.attributeFilter.includes('src'),'thumbnail resource churn is not text');
const empty={...foreign,textContent:''};
callback([{type:'attributes',attributeName:'style',target:empty}]);tick(500);assert.equal(read(),2);
window.__jusiTextStyles.set(foreign,Array(14).fill('').join('|'));
callback([{type:'attributes',attributeName:'style',target:foreign}]);tick(500);assert.equal(read(),2,'paint-only style leaves text intact');
foreign.style={display:'none'};
callback([{type:'attributes',attributeName:'class',target:foreign}]);tick(400);assert.equal(read(),3,'visibility changes refresh text');
for(let i=0;i<6;i++){callback([{type:'characterData',target:{nodeType:3,parentElement:foreign}}]);tick(250);}
assert.equal(read(),4,'continuous content changes flush within maximum batch interval');
console.log('document change observer tests passed');
