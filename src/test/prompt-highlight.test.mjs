import assert from 'node:assert/strict';
import {PromptHighlightResolver} from '../../dist/bridge/prompt-highlight.js';
import {commandText} from '../../dist/renderer/overlay-text.js';
const prompt={visible:true,prompt:'Value: ',promptHighlightId:42,level:1,indent:0,firstChar:'',content:'x',position:0};
const requests=[];let changed=0;
const resolver=new PromptHighlightResolver(id=>new Promise((resolve,reject)=>requests.push({id,resolve,reject})),()=>changed++);
const tick=()=>new Promise(resolve=>setImmediate(resolve));
assert.equal(resolver.update(prompt,0).promptHighlight,undefined);
assert.equal(requests[0].id,42);
resolver.update({...prompt,prompt:'Other: ',promptHighlightId:43},0);
assert.equal(requests.length,1,'at most one lookup in flight');
requests[0].resolve({fg:0xff0000});await tick();
assert.equal(changed,0,'old response discarded');assert.equal(requests[1].id,43);
requests[1].resolve({fg:0x123456,bold:true});await tick();
const resolved=resolver.update({...prompt,prompt:'Other: ',promptHighlightId:43},0);
assert.equal(resolved.promptHighlight.foreground,'#123456');
assert.equal(commandText(resolved).chunks[1].attrs.bold,true);
assert.equal(commandText(resolved).chunks[1].highlightId,0,'group ID never becomes attribute ID');
resolver.update({...prompt,prompt:'Other: ',promptHighlightId:43},1);
assert.equal(requests.length,3,'highlight redefinition refreshes lookup');
requests[2].reject(Error('unavailable'));await tick();
assert.equal(resolver.update({...prompt,prompt:'Other: ',promptHighlightId:43},1).promptHighlight,undefined);
assert.equal(requests.length,3,'failure cannot spin');
resolver.update(prompt,2);resolver.update({...prompt,visible:false},3);
requests[3].resolve({fg:0xffffff});await tick();assert.equal(changed,1);
resolver.update(prompt,4);resolver.dispose();requests[4].resolve({fg:0xffffff});await tick();assert.equal(changed,1);
assert.equal(resolved.promptHighlight.foreground,'#123456','prior snapshots immutable');
console.log('Prompt group resolution, stale replies, invalidation and failure fallback passed');
